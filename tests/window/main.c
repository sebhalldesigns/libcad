int main()
{

    printf("test...\n");

    cad_create_context();

    log_info("123");

    window_t window = window_create("123", 500, 500);

    gpu_init();

    while (window_update())
    {
        vec4 color;
        color[0] = 1.0f;
        color[1] = 0.0f;
        color[2] = 0.0f;
        color[3] = 1.0f;
        gpu_clear_color_buffer(color);
        
        window_swap_buffers();
    }

    return 0;
}

